ERROR_FILE_NOT_FOUND = 'FILE_NOT_FOUND'
ERROR_INVALID_ARGUMENT = 'INVALID_ARGUMENT'
ERROR_PROCESS_FAILED = 'PROCESS_FAILED'


@dataclass
class AppException(Exception):
    message: str
    error_code: str = ERROR_PROCESS_FAILED
    status_code: int = 400
    data: Any = None

    def __str__(self) -> str:
        return self.message
