ERROR_FACE_TOO_SMALL = 'FACE_TOO_SMALL'
ERROR_POSE_INVALID = 'POSE_INVALID'
ERROR_FACE_OCCLUDED = 'FACE_OCCLUDED'
ERROR_HEAD_CROPPED = 'HEAD_CROPPED'
ERROR_FACIAL_KEYPOINTS_INCOMPLETE = 'FACIAL_KEYPOINTS_INCOMPLETE'
